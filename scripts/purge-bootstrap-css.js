// Regenerates src/UI/bootstrap-subset.css: the rules of Bootstrap 5.0.2 that
// the config window can actually match.
//
// The window used to load all of bootstrap.min.css (194 KB) for some 45 classes,
// plus bootstrap.bundle.min.js and jQuery it never called. This keeps every rule
// whose selector can still match: a selector naming a class the window never
// uses is dropped (that class is never in the DOM, so the rule can never apply),
// as are the @keyframes nothing references. Everything else — :root variables,
// reboot, element rules, media queries — is kept verbatim and in order, so the
// cascade is unchanged.
//
// Run after adding a class to src/UI/index.html or to the renderer:
//   node scripts/purge-bootstrap-css.js
// Classes the renderer only ever adds at runtime are listed in RUNTIME_CLASSES.
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const SOURCE = path.join(__dirname, 'vendor', 'bootstrap-5.0.2.css');
const HTML = path.join(ROOT, 'src', 'UI', 'index.html');
const OUT = path.join(ROOT, 'src', 'UI', 'bootstrap-subset.css');

// Added by src/UI/js/app (status-models.ts and main.ts), never written in the HTML.
const RUNTIME_CLASSES = [
  'bg-primary',
  'bg-success',
  'bg-danger',
  'bg-secondary',
  'alert-info',
  'alert-warning',
  'alert-success',
  'alert-danger',
  'd-none',
];

function usedClasses() {
  const html = fs.readFileSync(HTML, 'utf8');
  const used = new Set(RUNTIME_CLASSES);
  for (const match of html.matchAll(/class="([^"]*)"/g)) {
    for (const name of match[1].split(/\s+/)) if (name) used.add(name);
  }
  return used;
}

/** Split CSS text into top-level statements: { prelude, body } or raw text. */
function parse(text) {
  const nodes = [];
  let i = 0;
  while (i < text.length) {
    // Skip whitespace and comments between statements.
    const rest = text.slice(i);
    const ws = /^(\s+|\/\*[\s\S]*?\*\/)/.exec(rest);
    if (ws) {
      i += ws[0].length;
      continue;
    }
    if (rest.startsWith('@charset')) {
      i += rest.indexOf(';') + 1;
      continue;
    }
    const open = text.indexOf('{', i);
    if (open === -1) break;
    const prelude = text.slice(i, open).trim();
    let depth = 1;
    let j = open + 1;
    while (j < text.length && depth > 0) {
      if (text[j] === '{') depth += 1;
      else if (text[j] === '}') depth -= 1;
      j += 1;
    }
    nodes.push({ prelude, body: text.slice(open + 1, j - 1) });
    i = j;
  }
  return nodes;
}

function splitSelectors(prelude) {
  const parts = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < prelude.length; i += 1) {
    const c = prelude[i];
    if (c === '(' || c === '[') depth += 1;
    else if (c === ')' || c === ']') depth -= 1;
    else if (c === ',' && depth === 0) {
      parts.push(prelude.slice(start, i).trim());
      start = i + 1;
    }
  }
  parts.push(prelude.slice(start).trim());
  return parts.filter(Boolean);
}

function canMatch(selector, used) {
  const withoutStrings = selector.replace(/\[[^\]]*\]/g, '[]');
  for (const match of withoutStrings.matchAll(/\.(-?[_a-zA-Z][_a-zA-Z0-9-]*)/g)) {
    if (!used.has(match[1])) return false;
  }
  return true;
}

function filter(nodes, used, indent = '') {
  const out = [];
  for (const node of nodes) {
    if (/^@(media|supports)/.test(node.prelude)) {
      const inner = filter(parse(node.body), used, `${indent}  `);
      if (inner.length) out.push(`${indent}${node.prelude} {\n${inner.join('\n')}\n${indent}}`);
      continue;
    }
    if (node.prelude.startsWith('@')) {
      out.push({ keyframes: node, indent });
      continue;
    }
    const kept = splitSelectors(node.prelude).filter((selector) => canMatch(selector, used));
    if (!kept.length) continue;
    const body = node.body
      .trim()
      .split(/\n/)
      .map((line) => `${indent}  ${line.trim()}`)
      .join('\n');
    out.push(`${indent}${kept.join(',\n' + indent)} {\n${body}\n${indent}}`);
  }
  return out;
}

function main() {
  const used = usedClasses();
  const source = fs.readFileSync(SOURCE, 'utf8');
  const header = /^[\s\S]*?\*\//.exec(source.replace(/^@charset "UTF-8";\s*/, ''))[0];
  const rules = filter(parse(source), used);
  const text = rules.filter((rule) => typeof rule === 'string').join('\n');
  // Keep an @-rule (keyframes) only when something kept still names it.
  const extra = rules
    .filter((rule) => typeof rule !== 'string')
    .filter(({ keyframes }) => {
      const name = keyframes.prelude.split(/\s+/)[1];
      return name && new RegExp(`\\b${name}\\b`).test(text);
    })
    .map(({ keyframes, indent }) => `${indent}${keyframes.prelude} {${keyframes.body}}`);
  const banner =
    '/* Generated by scripts/purge-bootstrap-css.js from Bootstrap 5.0.2 — do not edit. */\n';
  fs.writeFileSync(OUT, `@charset "UTF-8";\n${banner}${header}\n${[text, ...extra].join('\n')}\n`);
  const before = fs.statSync(SOURCE).size;
  const after = fs.statSync(OUT).size;
  console.log(`[purge-bootstrap-css] ${used.size} classes: ${before} -> ${after} bytes`);
}

main();
